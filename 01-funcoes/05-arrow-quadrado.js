// Crie uma Arrow Function que receba um número e retorne
// o quadrado desse número. Teste a função com o número 8.
//
// Escreva sua solução abaixo:

const calcularQuadrado = (numero) => numero ** 2;

// Teste da função com o número 8:
const resultado = calcularQuadrado(8);
console.log("O quadrado de 8 é:", resultado);